package canvasinputs

import "testing"

// golden 表由**实际执行前端 calculateResolution** 导出，不是推算的
// （见 resolution.go 的包注释）。几个凭直觉会写错的例子：
//
//	16:9 + 1080P → 1920x1088（不是 1920x1080：高度要 16 对齐）
//	9:16 + 1080P → 1088x1920
//	1:1  + 480P  → 848x480 （不是 854x480）
//	16:9 + 1920x1080 → 1920x1088（显式 WxH 分支同样 16 对齐，且忽略 ratio）
func TestCalculateResolutionMatchesFrontend(t *testing.T) {
	cases := []struct {
		ratio, base string
		wantStr     string
		wantW       int
		wantH       int
	}{
		{"1:1", "1K", "1024x1024", 1024, 1024},
		{"16:9", "720P", "1280x720", 1280, 720},
		{"16:9", "1080P", "1920x1088", 1920, 1088},
		{"9:16", "1K", "720x1280", 720, 1280},
		{"16:9", "1K", "1280x720", 1280, 720},
		{"Auto", "2K", "2048x2048", 2048, 2048},
		{"1:1", "4K", "4096x4096", 4096, 4096},
		{"16:9", "1920x1080", "1920x1088", 1920, 1088},
		{"乱七八糟", "1K", "1024x1024", 1024, 1024},
		{"1:1", "2K", "2048x2048", 2048, 2048},
		{"4:3", "1K", "1280x960", 1280, 960},
		{"3:4", "720P", "960x1280", 960, 1280},
		{"21:9", "1080P", "1920x816", 1920, 816},
		{"1:1", "480P", "848x480", 848, 480},
		{"16:9", "Auto", "1280x720", 1280, 720},
		{"Auto", "1K", "1024x1024", 1024, 1024},
		{"9:16", "1080P", "1088x1920", 1088, 1920},
		{"1:1", "", "1024x1024", 1024, 1024},
		{"16:9", "2K", "2048x1152", 2048, 1152},
		{"1:1", "1024x768", "1024x768", 1024, 768},
		{"16:9", "100x50", "96x48", 96, 48},
	}
	for _, c := range cases {
		got := CalculateResolution(c.ratio, c.base)
		if got.Str != c.wantStr || got.W != c.wantW || got.H != c.wantH {
			t.Errorf("CalculateResolution(%q, %q) = %+v, want {%s %d %d}",
				c.ratio, c.base, got, c.wantStr, c.wantW, c.wantH)
		}
	}
}
